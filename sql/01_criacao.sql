CREATE TABLE Paciente (
    id_paciente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    cpf VARCHAR(11) NOT NULL,
    email VARCHAR(255) UNIQUE,
    telefone VARCHAR(20) NOT NULL,
    data_nascimento DATE NOT NULL,

    CONSTRAINT uq_paciente_cpf UNIQUE (cpf),
    CONSTRAINT ck_paciente_cpf_formato CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_paciente_nascimento CHECK (data_nascimento <= CURRENT_DATE)
);

CREATE TABLE Profissional (
    id_profissional BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    crm VARCHAR(20) NOT NULL,
    email VARCHAR(255) UNIQUE,
    telefone VARCHAR(20) NOT NULL,
    situacao BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_profissional_crm UNIQUE (crm)
);

CREATE TABLE Especialidade (
    id_especialidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE,
    descricao TEXT
);

CREATE TABLE Sala (
    id_sala BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    andar VARCHAR(3) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    situacao BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE Procedimento (
    id_procedimento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT,
    valor_base NUMERIC(10,2) NOT NULL,

    CONSTRAINT ck_procedimento_valor CHECK (valor_base >= 0)
);

CREATE TABLE Profissional_Especialidade (
    id_profissional BIGINT NOT NULL,
    id_especialidade BIGINT NOT NULL,

    PRIMARY KEY (id_profissional, id_especialidade),

    CONSTRAINT fk_pe_profissional FOREIGN KEY (id_profissional)
        REFERENCES Profissional(id_profissional)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_pe_especialidade FOREIGN KEY (id_especialidade)
        REFERENCES Especialidade(id_especialidade)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE Consulta (
    id_consulta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora_inicio TIMESTAMP NOT NULL,
    data_hora_fim TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Agendada',
    observacoes TEXT,
    id_paciente BIGINT NOT NULL,
    id_profissional BIGINT NOT NULL,
    id_sala BIGINT NOT NULL,
    id_especialidade BIGINT NOT NULL,

    CONSTRAINT fk_consulta_paciente FOREIGN KEY (id_paciente)
        REFERENCES Paciente(id_paciente)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_consulta_profissional FOREIGN KEY (id_profissional)
        REFERENCES Profissional(id_profissional)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_consulta_sala FOREIGN KEY (id_sala)
        REFERENCES Sala(id_sala)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_consulta_especialidade FOREIGN KEY (id_especialidade)
        REFERENCES Especialidade(id_especialidade)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_consulta_prof_esp FOREIGN KEY (id_profissional, id_especialidade)
        REFERENCES Profissional_Especialidade(id_profissional, id_especialidade)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_consulta_status CHECK (status IN ('Agendada', 'Confirmada', 'Realizada', 'Cancelada')),
    CONSTRAINT ck_consulta_datas CHECK (data_hora_fim > data_hora_inicio)
);

CREATE TABLE Consulta_Procedimento (
    id_consulta BIGINT NOT NULL,
    id_procedimento BIGINT NOT NULL,
    quantidade INT NOT NULL DEFAULT 1,
    valor_cobrado NUMERIC(10,2) NOT NULL,

    PRIMARY KEY (id_consulta, id_procedimento),

    CONSTRAINT fk_cp_consulta FOREIGN KEY (id_consulta)
        REFERENCES Consulta(id_consulta)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_cp_procedimento FOREIGN KEY (id_procedimento)
        REFERENCES Procedimento(id_procedimento)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_cp_valor CHECK (valor_cobrado >= 0),
    CONSTRAINT ck_cp_quantidade CHECK (quantidade > 0)
);

CREATE INDEX idx_consulta_data
    ON Consulta(data_hora_inicio);

CREATE INDEX idx_consulta_profissional_data
    ON Consulta(id_profissional, data_hora_inicio);

CREATE INDEX idx_consulta_paciente_data
    ON Consulta(id_paciente, data_hora_inicio);

-- Impede duas consultas ativas na mesma sala exatamente no mesmo horário de início (RN04)
CREATE UNIQUE INDEX idx_sala_horario_unico
    ON Consulta(id_sala, data_hora_inicio)
    WHERE status <> 'Cancelada';
