
CREATE DATABASE Clinica;

CREATE TABLE Paciente (
    id_paciente bigint generated by default as identity primary key,
    nome VARCHAR(255) NOT NULL,
    cpf VARCHAR(11) not null,
    email VARCHAR(255),
    telefone VARCHAR(20),
    data_nascimento DATE NOT NULL

    CONSTRAINT uq_paciente_cpf UNIQUE (cpf)
);

CREATE TABLE Profissional (
    id_profissional bigint generated by default as identity primary key,
    nome VARCHAR(255) NOT NULL,
    crm VARCHAR(20) NOT NULL,
    email VARCHAR(255),
    telefone VARCHAR(255),
    situacao BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_profissional_crm UNIQUE (crm)
);

CREATE TABLE Especialidade (
    id_especialidade bigint generated by default as identity primary key,
    nome VARCHAR(255) NOT NULL,
    descricao TEXT
);

CREATE TABLE Sala (
    id_sala bigint generated by default as identity primary key,
    nome VARCHAR(50) NOT NULL,
    andar VARCHAR(3) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    situacao BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE Procedimento (
    id_procedimento bigint generated by default as identity primary key,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    valor_base NUMERIC(10,2) NOT NULL,

    CONSTRAINT ck_procedimento_valor
    CHECK (valor_base >= 0)

);

CREATE TABLE Profissional_Especialidade (
    id_profissional INT,
    id_especialidade INT,

    FOREIGN KEY (id_profissional)
    REFERENCES Profissional(id_profissional),

    FOREIGN KEY (id_especialidade)
    REFERENCES Especialidade(id_especialidade)
);


CREATE TABLE Consulta (
    id_consulta bigint generated by default as identity primary key,
    data_hora_inicio TIMESTAMP NOT NULL,
    data_hora_fim TIMESTAMP NOT NULL,
    status VARCHAR(255) NOT NULL,
    observacoes TEXT,
    id_paciente INT NOT NULL,
    id_profissional INT NOT NULL,
    id_sala INT NOT NULL,
    id_especialidade INT NOT NULL,

    FOREIGN KEY (id_paciente)
    REFERENCES Paciente(id_paciente),

    FOREIGN KEY (id_profissional)
    REFERENCES Profissional(id_profissional),

    FOREIGN KEY (id_sala)
    REFERENCES Sala(id_sala),

    FOREIGN KEY (id_especialidade)
    REFERENCES Especialidade(id_especialidade),

    CONSTRAINT ck_consulta_status
    CHECK (status IN ('Agendada', 'Realizada', 'Cancelada')),

    CONSTRAINT ck_consulta_datas
    CHECK (data_hora_fim > data_hora_inicio)

);

CREATE TABLE Consulta_Procedimento (
    id_consulta INT,
    id_procedimento INT,
    quantidade INT NOT NULL,
    valor_cobrado NUMERIC(10,2) NOT NULL,

    FOREIGN KEY (id_consulta)
    REFERENCES Consulta(id_consulta),

    FOREIGN KEY (id_procedimento)
    REFERENCES Procedimento(id_procedimento),

    CONSTRAINT ck_cp_valor
    CHECK (valor_cobrado >= 0),

    CONSTRAINT ck_cp_quantidade
    CHECK (quantidade > 0)

);


